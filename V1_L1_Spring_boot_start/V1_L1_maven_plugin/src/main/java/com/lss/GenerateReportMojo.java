package com.lss;

import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.text.SimpleDateFormat;
import java.util.Date;
import org.apache.maven.plugin.AbstractMojo;
import org.apache.maven.plugin.MojoExecutionException;
import org.apache.maven.plugin.MojoFailureException;
import org.apache.maven.plugins.annotations.LifecyclePhase;
import org.apache.maven.plugins.annotations.Mojo;
import org.apache.maven.plugins.annotations.Parameter;
import org.apache.maven.project.MavenProject;

/**
 * Goal that generates a simple HTML build report.
 */
@Mojo(name = "generate-report", defaultPhase = LifecyclePhase.PACKAGE) // <--- Назва цілі і фаза за замовчуванням
public class GenerateReportMojo extends AbstractMojo {

    /**
     * The Maven project itself. Injected by Maven.
     */
    @Parameter(defaultValue = "${project}", readonly = true, required = true) // <--- Ін'єкція об'єкта MavenProject
    private MavenProject project;

    /**
     * The directory where the report file will be generated.
     */
    @Parameter(defaultValue = "${project.build.directory}", property = "report.outputDir", required = true)
    private File outputDirectory;

    /**
     * The name of the report file.
     */
    @Parameter(defaultValue = "build-report.html", property = "report.fileName")
    private String fileName;

    @Override
    public void execute() throws MojoExecutionException, MojoFailureException {
        getLog().info("Starting custom build report generation...");
        // Перевіряємо, чи існує вихідна директорія, якщо ні - створюємо її
        if (!outputDirectory.exists()) {
            outputDirectory.mkdirs();
        }
        File reportFile = new File(outputDirectory, fileName);
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
        String currentTime = sdf.format(new Date());

        // Формуємо вміст HTML звіту
        StringBuilder htmlContent = new StringBuilder();
        htmlContent.append("<!DOCTYPE html>\n");
        htmlContent.append("<html lang=\"en\">\n");
        htmlContent.append("<head>\n");
        htmlContent.append("    <meta charset=\"UTF-8\">\n");
        htmlContent.append("    <title>Build Report</title>\n");
        htmlContent.append("    <style>\n");
        htmlContent.append("        body { font-family: Arial, sans-serif; margin: 20px; background-color: #f4f4f4; }\n");
        htmlContent.append("        .container { background-color: #fff; padding: 20px; border-radius: 8px; box-shadow: 0 0 10px rgba(0, 0, 0, 0.1); }\n");
        htmlContent.append("        h1 { color: #333; }\n");
        htmlContent.append("        p { line-height: 1.6; }\n");
        htmlContent.append("    </style>\n");
        htmlContent.append("</head>\n");
        htmlContent.append("<body>\n");
        htmlContent.append("    <div class=\"container\">\n");
        htmlContent.append("        <h1>Project Build Report</h1>\n");
        htmlContent.append("        <p><strong>Project Name:</strong> ").append(project.getName()).append("</p>\n");
        htmlContent.append("        <p><strong>Project ID:</strong> ").append(project.getGroupId()).append(":").append(project.getArtifactId()).append("</p>\n");
        htmlContent.append("        <p><strong>Version:</strong> ").append(project.getVersion()).append("</p>\n");
        htmlContent.append("        <p><strong>Build Date:</strong> ").append(currentTime).append("</p>\n");
        htmlContent.append("        <hr/>\n");
        htmlContent.append("        <p>This report was generated by my custom Maven plugin.</p>\n");
        htmlContent.append("    </div>\n");
        htmlContent.append("</body>\n");
        htmlContent.append("</html>");
        try (FileWriter writer = new FileWriter(reportFile)) {
            writer.write(htmlContent.toString());
            getLog().info("Custom build report generated successfully at: " + reportFile.getAbsolutePath());
        } catch (IOException e) {
            getLog().error("Failed to generate report: " + e.getMessage(), e);
            throw new MojoExecutionException("Error generating build report.", e);
        }
    }
}
